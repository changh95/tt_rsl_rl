"""Phase 8.1 device tests on a multi-chip mesh: a heteroscedastic actor (state-dependent std stored per sample, std head trained through the MLP) under the data-parallel
semantics of ADR-0004. The same three properties as `test_tt_multichip.py`: N chips equal 1 chip on the union mini-batch (function space), replicas stay bit-identical,
traced == eager.

    scripts/tt_run.sh --chips 16,17 --timeout 900 --tag p8m -- env TT_TEST_MESH=1x2 python -m pytest -m tt tests/tt/test_tt_hetero_multichip.py -q -p no:cacheprovider
    scripts/tt_run.sh --timeout 900 --tag p8m -- env TT_TEST_MESH=2x4 python -m pytest -m tt tests/tt/test_tt_hetero_multichip.py -q -p no:cacheprovider

The 1-chip reference `tests/tt/data/mc_step_reference_hetero.npz` is generated by `scripts/mc_step_reference.py --hetero`.
"""

from pathlib import Path

import pytest
import torch

from rsl_rl_tt.testing import mc_equiv
from rsl_rl_tt.testing.reference import test_mesh_shape

_ROWS, _COLS = test_mesh_shape()
pytestmark = [pytest.mark.tt, pytest.mark.skipif(_ROWS * _COLS == 1, reason="needs a multi-chip mesh (TT_TEST_MESH=1x2 or 2x4)")]

DATA = Path(__file__).parent / "data"
N = _ROWS * _COLS
HETERO = "HeteroscedasticGaussianDistribution"


def test_update_step_equals_one_chip_on_the_union_minibatch(tt_mesh):
    """N chips vs 1 chip on the same global sample set (3 mini-batch steps; loss -> gradient exchange -> per-model clip -> Adam, adaptive LR from the mean KL, the KL
    using every sample's stored std). The outputs of the actor's two heads (mean and std) and the critic after the steps agree to a small fraction of the update size."""
    ref_path = DATA / mc_equiv.REFERENCE_HETERO
    assert ref_path.exists(), "generate the 1-chip reference first: scripts/tt_run.sh --chips 16 -- python scripts/mc_step_reference.py --hetero"
    ref = mc_equiv.load_reference(ref_path)
    runner = mc_equiv.make_runner([_ROWS, _COLS], hetero=True)
    alg = runner.alg
    assert alg.hetero
    pool, obs = mc_equiv.make_pool(alg)
    res = mc_equiv.run_steps(alg, pool, obs)
    for tag in ("actor", "critic"):
        d = float((res[f"{tag}_before"] - ref[f"{tag}_before"]).abs().max())
        assert d <= mc_equiv.FORWARD_ATOL, f"{tag}: the forward pass on {N} chips differs from the 1-chip forward by {d:.3e} (limit {mc_equiv.FORWARD_ATOL})"
    assert res["lrs"] == ref["lrs"], f"the adaptive learning rate took different decisions: {res['lrs']} vs {ref['lrs']}"
    report = {}
    for tag in ("actor", "critic"):
        moved = float((ref[f"{tag}_after"] - ref[f"{tag}_before"]).abs().max())
        dev = float((res[f"{tag}_after"] - ref[f"{tag}_after"]).abs().max())
        report[tag] = (dev, moved, dev / moved)
        assert moved > 0
    print("\nN chips vs 1 chip, heteroscedastic (function-space deviation, update size, ratio):", {k: tuple(f"{x:.3e}" for x in v) for k, v in report.items()})
    for tag, (dev, moved, ratio) in report.items():
        assert ratio <= mc_equiv.TOLERANCE, f"{tag}: the {N}-chip result deviates by {ratio:.3e} of the update size (limit {mc_equiv.TOLERANCE})"
    assert alg.replica_max_diff() == 0.0, "the replicas differ after the steps"


def build_runner(trace=False, interval=0, std_type="scalar", seed=0):
    from rsl_rl.runners import OnPolicyRunner
    from rsl_rl_tt.testing.envs import make_env
    from rsl_rl_tt.testing.reference import make_train_cfg
    from tests.tt.test_tt_rollout import small_spec

    spec = small_spec("cartpole", num_envs=max(128, 32 * N), distribution=HETERO, std_type=std_type, init_std=0.8)
    torch.manual_seed(seed)
    env = make_env("cartpole", spec.num_envs, seed=seed)
    cfg = make_train_cfg("cartpole", spec)
    cfg["algorithm"]["class_name"] = "rsl_rl_tt.ppo:TTPPO"
    cfg["algorithm"]["tt_cfg"] = {"mesh_shape": [_ROWS, _COLS], "trace": trace, "replica_check_interval": interval}
    return OnPolicyRunner(env, cfg, log_dir=None, device="cpu"), env


@pytest.mark.parametrize("trace", [False, True])
def test_replicas_stay_bit_identical_over_training(tt_mesh, trace):
    """After K iterations every chip holds identical parameters (incl. the std head), Adam state, normalizer statistics and learning rate (checked every update)."""
    runner, _ = build_runner(trace=trace, interval=1)
    try:
        runner.learn(num_learning_iterations=3)  # raises RuntimeError by itself if the replicas diverge
        assert runner.alg.replica_max_diff() == 0.0
    finally:
        runner.alg.release_traces()


def test_traced_training_is_bit_identical_to_eager_on_several_chips(tt_mesh):
    eager, _ = build_runner(trace=False, std_type="log")
    traced, _ = build_runner(trace=True, std_type="log")
    from tests.tt.test_tt_trace import assert_state_equal, host_state

    try:
        torch.manual_seed(4242)
        eager.learn(num_learning_iterations=3)
        torch.manual_seed(4242)
        traced.learn(num_learning_iterations=3)
        assert {"act", "gae", "update.step.0"} <= set(traced.alg._traces)
        assert_state_equal(host_state(eager.alg), host_state(traced.alg), "eager vs traced on several chips (heteroscedastic)")
        assert traced.alg.replica_max_diff() == 0.0
    finally:
        traced.alg.release_traces()
