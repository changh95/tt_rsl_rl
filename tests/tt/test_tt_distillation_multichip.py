"""Phase 8.4 device tests on a multi-chip mesh: the distillation under the data-parallel semantics of ADR-0004. N chips equal 1 chip on the same stored rollout (the loss of a chip is the mean
over its rows, the gradients are averaged over the chips before the clip: the gradient of the global mean), replicas stay bit-identical, traced == eager.

    scripts/tt_run.sh --chips 16,17 --timeout 900 --tag p8dm -- env TT_TEST_MESH=1x2 python -m pytest -m tt tests/tt/test_tt_distillation_multichip.py -q -p no:cacheprovider
    scripts/tt_run.sh --timeout 900 --tag p8dm -- env TT_TEST_MESH=2x4 python -m pytest -m tt tests/tt/test_tt_distillation_multichip.py -q -p no:cacheprovider

The 1-chip reference `tests/tt/data/mc_step_reference_distill.npz` is generated by `scripts/mc_distill_reference.py`.
"""

from pathlib import Path

import pytest
import torch

from rsl_rl_tt.testing import distill_equiv
from rsl_rl_tt.testing.reference import make_teacher_checkpoint, test_mesh_shape
from tests.tt.test_tt_distillation import teachers  # noqa: F401  (a fixture)

_ROWS, _COLS = test_mesh_shape()
pytestmark = [pytest.mark.tt, pytest.mark.skipif(_ROWS * _COLS == 1, reason="needs a multi-chip mesh (TT_TEST_MESH=1x2 or 2x4)")]

DATA = Path(__file__).parent / "data"
N = _ROWS * _COLS


@pytest.fixture(scope="module")
def mc_teacher(tmp_path_factory):
    # the same teacher as the 1-chip reference: the seeded upstream CPU run of scripts/mc_distill_reference.py
    return make_teacher_checkpoint(distill_equiv.ENV, str(tmp_path_factory.mktemp("mc") / "t.pt"), seed=0, iterations=5, num_envs=128)


def test_update_equals_one_chip_on_the_same_rollout(tt_mesh, mc_teacher):
    ref_path = DATA / distill_equiv.REFERENCE
    assert ref_path.exists(), "generate the 1-chip reference first: scripts/tt_run.sh --chips 16 -- python scripts/mc_distill_reference.py"
    ref = distill_equiv.load_reference(ref_path)
    runner = distill_equiv.make_runner([_ROWS, _COLS], mc_teacher)
    alg = runner.alg
    res = distill_equiv.run_update(alg)
    d = float((res["before"] - ref["before"]).abs().max())
    assert d <= distill_equiv.FORWARD_ATOL, f"the forward pass on {N} chips differs from the 1-chip forward by {d:.3e} (limit {distill_equiv.FORWARD_ATOL})"
    moved = float((ref["after"] - ref["before"]).abs().max())
    dev = float((res["after"] - ref["after"]).abs().max())
    print(f"\nN chips vs 1 chip, distillation (function-space deviation, update size, ratio): {dev:.3e} {moved:.3e} {dev / moved:.3e}; loss {res['loss']:.6f} vs {ref['loss']:.6f}")
    assert moved > 0 and dev / moved <= distill_equiv.TOLERANCE, f"the {N}-chip result deviates by {dev / moved:.3e} of the update size (limit {distill_equiv.TOLERANCE})"
    assert res["loss"] == pytest.approx(ref["loss"], rel=2e-2)
    assert alg.replica_max_diff() == 0.0, "the replicas differ after the update"


def build_runner(teachers, trace=False, interval=0, seed=0):
    import dataclasses

    from rsl_rl_tt.testing.reference import REF_SPECS, build_distillation_runner

    spec = dataclasses.replace(REF_SPECS["cartpole"], num_envs=max(128, 32 * N), num_steps=8, iterations=1)
    runner, env, _ = build_distillation_runner("cartpole", seed, None, teachers["cartpole"], tt=True, tt_cfg={"trace": trace, "replica_check_interval": interval},
                                               algorithm=dict(num_learning_epochs=2, gradient_length=6, max_grad_norm=1.0), spec=spec)
    return runner, env


@pytest.mark.parametrize("trace", [False, True])
def test_replicas_stay_bit_identical_over_training(tt_mesh, teachers, trace):
    runner, _ = build_runner(teachers, trace=trace, interval=1)
    try:
        runner.learn(num_learning_iterations=3)  # raises RuntimeError by itself if the replicas diverge
        assert runner.alg.replica_max_diff() == 0.0
    finally:
        runner.alg.release_traces()


def test_traced_training_is_bit_identical_to_eager_on_several_chips(tt_mesh, teachers):
    eager, _ = build_runner(teachers, trace=False)
    traced, _ = build_runner(teachers, trace=True)
    from tests.tt.test_tt_distillation_trace import assert_equal, host_state

    try:
        torch.manual_seed(4242)
        eager.learn(num_learning_iterations=3)
        torch.manual_seed(4242)
        traced.learn(num_learning_iterations=3)
        assert {"act", "distill.apply", "distill.step.0"} <= set(traced.alg._traces)
        assert_equal(host_state(eager.alg), host_state(traced.alg), "eager vs traced on several chips (distillation)")
        assert traced.alg.replica_max_diff() == 0.0
    finally:
        traced.alg.release_traces()
