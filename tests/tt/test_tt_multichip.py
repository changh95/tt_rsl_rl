"""Phase 6 device tests: tray multi-chip data parallel (ADR-0004; BRIEF 3.6): parameters and Adam state replicated, the batch sharded over the chips, gradients and the
KL averaged over the chips, global observation-normalizer statistics, chip-local advantage normalisation and shuffling.

    scripts/tt_run.sh --chips 16,17 --timeout 900 --tag p6_1x2 -- env TT_TEST_MESH=1x2 python -m pytest -m tt tests/tt/test_tt_multichip.py -q -p no:cacheprovider
    scripts/tt_run.sh --timeout 900 --tag p6_2x4 -- env TT_TEST_MESH=2x4 python -m pytest -m tt tests/tt/test_tt_multichip.py -q -p no:cacheprovider

The chip-count independent suites (forward / rollout / checkpoint / normalizer of tests/tt) run on the same meshes; the Phase 3 whole-batch references do not apply here
(see conftest.py). N chips vs ONE chip: the 1-chip reference `tests/tt/data/mc_step_reference.pt` is generated by `scripts/mc_step_reference.py`.
"""

from pathlib import Path

import pytest
import torch

from rsl_rl_tt.testing import mc_equiv
from rsl_rl_tt.testing.reference import test_mesh_shape

_ROWS, _COLS = test_mesh_shape()
pytestmark = [pytest.mark.tt, pytest.mark.skipif(_ROWS * _COLS == 1, reason="needs a multi-chip mesh (TT_TEST_MESH=1x2 or 2x4)")]

DATA = Path(__file__).parent / "data"
N = _ROWS * _COLS


def per_chip_equal(ctx, tensor) -> bool:
    copies = ctx.per_chip(tensor)
    return all(torch.equal(copies[0], copies[i]) for i in range(1, copies.shape[0]))


def test_exactly_the_selected_nodes_are_open(tt_mesh):
    """BRIEF Phase 6: the open nodes are exactly the chips of the job (all eight tray nodes on the 2x4 mesh), nothing else."""
    from rsl_rl_tt.device import list_open_tt_nodes

    assert list_open_tt_nodes() == {f"/dev/tenstorrent/{c}" for c in tt_mesh.cfg.chips}
    assert len(tt_mesh.cfg.chips) == N
    if N == 8:
        assert set(tt_mesh.cfg.chips) == set(range(16, 24))


@pytest.mark.parametrize("shape", [(512, 256), (64, 128), (1, 256), (1, 1)])
def test_cross_chip_sum_and_mean_are_fp32_accurate_and_identical_on_every_chip(tt_ctx, shape):
    """ADR-0004 A-1: all_gather along every mesh axis + fp32 `ttnn.sum`: ~1e-7 against float64 (the stock all_reduce has 5.5e-4) and bit-identical replicas."""
    r, c = shape
    rp, cp = max(r, 32), max(c, 32)
    g = torch.Generator().manual_seed(11)
    host = torch.randn(N * rp, cp, generator=g) * torch.logspace(-2, 1, N).repeat_interleave(rp).reshape(-1, 1)  # chips with different gradient scales
    x = tt_ctx.upload(host, op="H-6", batch_sharded=True)
    x = x[0:r, 0:c] if (r, c) != (rp, cp) else x
    ref = host.reshape(N, rp, cp)[:, :r, :c].double()
    for name, out, want in (("mean", tt_ctx.mean_over_chips(x), ref.mean(0)), ("sum", tt_ctx.sum_over_chips(x), ref.sum(0))):
        copies = tt_ctx.per_chip(out)
        copies = copies.reshape(N, -1, copies.shape[-1])[:, :r, :c]
        rel = float((copies[0].double() - want).abs().max() / want.abs().max())
        assert rel < 1e-6, f"{name} {shape}: rel err {rel:.2e}"
        assert all(torch.equal(copies[0], copies[i]) for i in range(1, N)), f"{name} {shape}: the chips hold different results"


def test_normalizer_statistics_are_global_and_identical_on_every_chip(tt_ctx):
    """Each chip sees different observations; the statistics are those of the union and every chip holds the very same values (upstream: all-reduced)."""
    from rsl_rl.modules.normalization import EmpiricalNormalization
    from rsl_rl_tt.modules import TTEmpiricalNormalization
    from rsl_rl_tt.tt_common import pad_matrix, pad_up

    dim = 36
    ref, tt = EmpiricalNormalization(dim), TTEmpiricalNormalization(tt_ctx, EmpiricalNormalization(dim), dim)
    for i in range(4):
        local = 64
        # chip c draws from a different distribution (shifted mean, different scale): local statistics differ a lot, global ones are the union's
        x = torch.cat([torch.randn(local, dim, generator=torch.Generator().manual_seed(10 * i + c)) * (1.0 + c) + 2.0 * c for c in range(N)])
        ref.update(x)
        tt.update(tt_ctx.upload(pad_matrix(x, x.shape[0], pad_up(dim)), op="H-1", batch_sharded=True), local)
    s = tt.host_stats()
    assert torch.allclose(s["mean"], ref.mean, rtol=1e-4, atol=1e-5) and torch.allclose(s["var"], ref._var.reshape(-1), rtol=1e-4, atol=1e-5)
    assert per_chip_equal(tt_ctx, tt._mean) and per_chip_equal(tt_ctx, tt._var)


def test_shuffle_permutes_each_chips_own_rows(tt_ctx):
    """Every chip applies its OWN local permutation to its own shard (upstream: an independent randperm per rank): bit-exact, no row crosses a chip."""
    from rsl_rl_tt.storage import TTRolloutStorage

    steps, envs = 4, 32 * N
    st = TTRolloutStorage(tt_ctx, envs, steps, 32, 32, 32, True)
    n_local, w = st.local_batch_size, st.width
    g = torch.Generator().manual_seed(5)
    table = torch.randn(N * n_local, w, generator=g)
    perms = [torch.randperm(n_local, generator=g) for _ in range(N)]
    out = tt_ctx.download(st.shuffle(tt_ctx.upload(table, op="H-1", batch_sharded=True), tt_ctx.upload_index(torch.cat(perms), op="H-4")), op="H-6")
    for c in range(N):
        want = table[c * n_local : (c + 1) * n_local][perms[c]]
        assert torch.equal(out[c * n_local : (c + 1) * n_local], want), f"chip {c}: the shuffled rows are not its own permuted rows"


def test_update_step_equals_one_chip_on_the_union_minibatch(tt_mesh):
    """BRIEF Phase 6: N chips vs 1 chip on the same global sample set. K = 3 mini-batch steps (loss -> gradient exchange -> per-model clip -> Adam, adaptive LR from the
    mean KL) on N chips, each chip stepping on its slice of every union mini-batch, against the 1-chip run on the union mini-batches themselves
    (`tests/tt/data/mc_step_reference.pt`, `scripts/mc_step_reference.py`). The two differ only by floating-point summation order (mean of the chips' means vs one
    mean), so the policy and value outputs after the steps must agree to a small fraction of how far the steps moved them (function space: Adam turns tiny gradient
    differences of near-zero elements into full-size steps, so a parameter-by-parameter comparison would be meaningless; the Phase 3 tests do the same)."""
    ref_path = DATA / mc_equiv.REFERENCE
    assert ref_path.exists(), "generate the 1-chip reference first: scripts/tt_run.sh --chips 16 -- python scripts/mc_step_reference.py"
    ref = mc_equiv.load_reference(ref_path)
    runner = mc_equiv.make_runner([_ROWS, _COLS])
    alg = runner.alg
    pool, obs = mc_equiv.make_pool(alg)
    res = mc_equiv.run_steps(alg, pool, obs)
    # Same parameters, same rows, different rows PER CHIP (768 vs 1536 at 2 chips): the fp32 matmul program is configured per chip row count, so a few outputs differ in the
    # accumulation order (probe `scripts/probe_rows_per_chip.py`: 68 of 18432 actor values, max 1.2e-4, against 1.7e-3 vs float64 for BOTH runs; TTNN_ISSUES T-14).
    # The bound is below the matmul noise floor of TOLERANCES.md and ~8x the observation.
    for tag in ("actor", "critic"):
        d = float((res[f"{tag}_before"] - ref[f"{tag}_before"]).abs().max())
        assert d <= mc_equiv.FORWARD_ATOL, f"{tag}: the forward pass on {N} chips differs from the 1-chip forward by {d:.3e} (limit {mc_equiv.FORWARD_ATOL})"
    assert res["lrs"] == ref["lrs"], f"the adaptive learning rate took different decisions: {res['lrs']} vs {ref['lrs']}"
    report = {}
    for tag in ("actor", "critic"):
        moved = float((ref[f"{tag}_after"] - ref[f"{tag}_before"]).abs().max())
        dev = float((res[f"{tag}_after"] - ref[f"{tag}_after"]).abs().max())
        report[tag] = (dev, moved, dev / moved)
        assert moved > 0
    print("\nN chips vs 1 chip (function-space deviation, update size, ratio):", {k: tuple(f"{x:.3e}" for x in v) for k, v in report.items()})
    for tag, (dev, moved, ratio) in report.items():
        assert ratio <= mc_equiv.TOLERANCE, f"{tag}: the {N}-chip result deviates by {ratio:.3e} of the update size (limit {mc_equiv.TOLERANCE})"
    assert alg.replica_max_diff() == 0.0, "the replicas differ after the steps"


def build_runner(trace=False, interval=0, num_envs=None, seed=0):
    from rsl_rl.runners import OnPolicyRunner
    from rsl_rl_tt.testing.envs import make_env
    from rsl_rl_tt.testing.reference import make_train_cfg
    from tests.tt.test_tt_rollout import small_spec

    spec = small_spec("cartpole", num_envs=num_envs or max(128, 32 * N))
    torch.manual_seed(seed)
    env = make_env("cartpole", spec.num_envs, seed=seed)
    cfg = make_train_cfg("cartpole", spec)
    cfg["algorithm"]["class_name"] = "rsl_rl_tt.ppo:TTPPO"
    cfg["algorithm"]["tt_cfg"] = {"mesh_shape": [_ROWS, _COLS], "trace": trace, "replica_check_interval": interval}
    return OnPolicyRunner(env, cfg, log_dir=None, device="cpu"), env


def test_advantages_are_normalised_per_chip(tt_mesh):
    """ADR-0004: advantage normalisation is chip-LOCAL (rank-local in upstream multi-GPU): every chip's advantages have mean 0 and unbiased std 1 on their own."""
    runner, env = build_runner()
    alg = runner.alg
    alg.train_mode()
    obs = env.get_observations()
    with torch.inference_mode():
        for _ in range(alg.storage.num_transitions_per_env):
            actions = alg.act(obs)
            obs, rewards, dones, extras = env.step(actions)
            alg.process_env_step(obs, rewards, dones, extras)
        alg.compute_returns(obs)
    adv = alg.ctx.per_chip(alg.storage.advantages)[:, :, 0]  # [chips, local rows]
    for c in range(N):
        assert abs(float(adv[c].mean())) < 1e-4 and abs(float(adv[c].std()) - 1.0) < 1e-4, f"chip {c}: mean {float(adv[c].mean()):.2e}, std {float(adv[c].std()):.6f}"
    alg.release_traces()


@pytest.mark.parametrize("trace", [False, True])
def test_replicas_stay_bit_identical_over_training_and_a_corrupted_replica_is_detected(tt_mesh, trace):
    """BRIEF Phase 6: after K iterations every chip holds identical parameters, Adam state, normalizer statistics and learning rate (checked every update by the
    built-in check); and the check really notices a replica that drifted."""
    runner, env = build_runner(trace=trace, interval=1)
    try:
        runner.learn(num_learning_iterations=3)  # raises RuntimeError by itself if the replicas diverge
        alg = runner.alg
        assert alg.replica_max_diff() == 0.0
        # corrupt ONE chip's copy of a weight: chip c gets its own values, the others keep the replicated ones
        layer = alg.tt_actor.mlp.layers[0]
        shape = tuple(layer.w.shape)
        stacked = alg.ctx.per_chip(layer.w).reshape(N * shape[0], shape[1]).clone()
        stacked[shape[0] * (N - 1)] += 1e-3  # the last chip's first row differs
        alg.ctx.upload_into(layer.w, stacked, op="H-6", batch_sharded=True)
        assert alg.replica_max_diff() > 0.0
        with pytest.raises(RuntimeError, match="replicas"):
            runner.learn(num_learning_iterations=1)
    finally:
        runner.alg.release_traces()


def test_traced_training_is_bit_identical_to_eager_on_several_chips(tt_mesh):
    """The captured traces (with the gradient exchange inside) reproduce the eager multi-chip path bit for bit."""
    eager, _ = build_runner(trace=False)
    traced, _ = build_runner(trace=True)
    from tests.tt.test_tt_trace import assert_state_equal, host_state

    try:
        torch.manual_seed(4242)
        eager.learn(num_learning_iterations=3)
        torch.manual_seed(4242)
        traced.learn(num_learning_iterations=3)
        assert {"act", "gae", "update.step.0"} <= set(traced.alg._traces)
        assert_state_equal(host_state(eager.alg), host_state(traced.alg), "eager vs traced on several chips")
        assert traced.alg.replica_max_diff() == 0.0
    finally:
        traced.alg.release_traces()
