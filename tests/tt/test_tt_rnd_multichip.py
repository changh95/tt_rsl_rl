"""Phase 8.2 device tests on a multi-chip mesh: RND under the data-parallel semantics of ADR-0004 (the predictor's gradients are averaged over the chips like the actor's and the
critic's, the normalizer statistics are global, the discounted-reward accumulator is local). The three properties of `test_tt_multichip.py`: N chips equal 1 chip on the union
mini-batch (function space, predictor included), replicas stay bit-identical, traced == eager.

    scripts/tt_run.sh --chips 16,17 --timeout 900 --tag p8rm -- env TT_TEST_MESH=1x2 python -m pytest -m tt tests/tt/test_tt_rnd_multichip.py -q -p no:cacheprovider
    scripts/tt_run.sh --timeout 900 --tag p8rm -- env TT_TEST_MESH=2x4 python -m pytest -m tt tests/tt/test_tt_rnd_multichip.py -q -p no:cacheprovider

The 1-chip reference `tests/tt/data/mc_step_reference_rnd.npz` is generated by `scripts/mc_step_reference.py --rnd`.
"""

from pathlib import Path

import pytest
import torch

from rsl_rl_tt.testing import mc_equiv
from rsl_rl_tt.testing.reference import test_mesh_shape

_ROWS, _COLS = test_mesh_shape()
pytestmark = [pytest.mark.tt, pytest.mark.skipif(_ROWS * _COLS == 1, reason="needs a multi-chip mesh (TT_TEST_MESH=1x2 or 2x4)")]

DATA = Path(__file__).parent / "data"
N = _ROWS * _COLS


def test_update_step_equals_one_chip_on_the_union_minibatch(tt_mesh):
    """N chips vs 1 chip on the same global sample set (3 mini-batch steps: the PPO step and the predictor's step, both with the gradient exchange; the adaptive learning rate from the
    mean KL). The actor mean, the critic value and the predictor's embedding after the steps agree to a small fraction of the update size."""
    ref_path = DATA / mc_equiv.REFERENCE_RND
    assert ref_path.exists(), "generate the 1-chip reference first: scripts/tt_run.sh --chips 16 -- python scripts/mc_step_reference.py --rnd"
    ref = mc_equiv.load_reference(ref_path)
    runner = mc_equiv.make_runner([_ROWS, _COLS], rnd=True)
    alg = runner.alg
    pool, obs = mc_equiv.make_pool(alg)
    res = mc_equiv.run_steps(alg, pool, obs)
    for tag in ("actor", "critic", "rnd"):
        d = float((res[f"{tag}_before"] - ref[f"{tag}_before"]).abs().max())
        assert d <= mc_equiv.FORWARD_ATOL, f"{tag}: the forward pass on {N} chips differs from the 1-chip forward by {d:.3e} (limit {mc_equiv.FORWARD_ATOL})"
    assert res["lrs"] == ref["lrs"], f"the adaptive learning rate took different decisions: {res['lrs']} vs {ref['lrs']}"
    report = {}
    for tag in ("actor", "critic", "rnd"):
        moved = float((ref[f"{tag}_after"] - ref[f"{tag}_before"]).abs().max())
        dev = float((res[f"{tag}_after"] - ref[f"{tag}_after"]).abs().max())
        report[tag] = (dev, moved, dev / moved)
        assert moved > 0
    print("\nN chips vs 1 chip, RND (function-space deviation, update size, ratio):", {k: tuple(f"{x:.3e}" for x in v) for k, v in report.items()})
    for tag, (dev, moved, ratio) in report.items():
        assert ratio <= mc_equiv.TOLERANCE, f"{tag}: the {N}-chip result deviates by {ratio:.3e} of the update size (limit {mc_equiv.TOLERANCE})"
    assert alg.replica_max_diff() == 0.0, "the replicas differ after the steps"


def build_runner(trace=False, interval=0, seed=0):
    from rsl_rl.runners import OnPolicyRunner
    from rsl_rl_tt.testing.envs import make_env
    from rsl_rl_tt.testing.reference import make_train_cfg
    from tests.tt.test_tt_rnd import rnd_spec

    name, spec = rnd_spec("cartpole-actor")
    torch.manual_seed(seed)
    env = make_env(name, spec.num_envs, seed=seed)
    cfg = make_train_cfg(name, spec)
    cfg["algorithm"]["class_name"] = "rsl_rl_tt.ppo:TTPPO"
    cfg["algorithm"]["tt_cfg"] = {"mesh_shape": [_ROWS, _COLS], "trace": trace, "replica_check_interval": interval}
    return OnPolicyRunner(env, cfg, log_dir=None, device="cpu"), env


@pytest.mark.parametrize("trace", [False, True])
def test_replicas_stay_bit_identical_over_training(tt_mesh, trace):
    """After K iterations every chip holds identical parameters, Adam state, normalizer statistics and learning rate, and identical RND state (predictor, target, its Adam moments, the
    global state / reward statistics): checked after every update (`replica_max_diff` includes RND)."""
    runner, _ = build_runner(trace=trace, interval=1)
    try:
        runner.learn(num_learning_iterations=3, init_at_random_ep_len=True)  # raises RuntimeError by itself if the replicas diverge
        assert runner.alg.replica_max_diff() == 0.0
        assert runner.alg.rnd_tt.tensors()
    finally:
        runner.alg.release_traces()


def test_traced_training_is_bit_identical_to_eager_on_several_chips(tt_mesh):
    eager, _ = build_runner(trace=False)
    traced, _ = build_runner(trace=True)
    from tests.tt.test_tt_rnd_trace import full_state
    from tests.tt.test_tt_trace import assert_state_equal

    try:
        torch.manual_seed(4242)
        eager.learn(num_learning_iterations=3, init_at_random_ep_len=True)
        torch.manual_seed(4242)
        traced.learn(num_learning_iterations=3, init_at_random_ep_len=True)
        assert {"act", "gae", "update.step.0"} <= set(traced.alg._traces)
        assert_state_equal(full_state(eager.alg), full_state(traced.alg), "eager vs traced on several chips (RND)")
        assert torch.equal(eager.alg.intrinsic_rewards, traced.alg.intrinsic_rewards)
        assert traced.alg.replica_max_diff() == 0.0
    finally:
        traced.alg.release_traces()
