"""Phase 8.4: N chips vs ONE chip for the distillation update (BRIEF Phase 6 test design, ADR-0004), on identical synthetic data.

A distillation step is the whole batch of one time index (all environments), split over the chips like every batch-sharded tensor; the loss of a chip is the mean over ITS rows, the gradients
are averaged over the chips before the clip: on the same global batch that is the gradient of the global mean, whatever the chip count. So one `update()` on the same stored rollout must give
the same student on 1, 2 and 8 chips up to floating-point summation order. The rollout is synthetic (observations ~ N(0, 1), the teacher's actions from the teacher's torch forward); the 1-chip
reference is generated by `scripts/mc_step_reference.py --distill` and committed under `tests/tt/data/`.
"""

from __future__ import annotations

from typing import Any

import torch
from tensordict import TensorDict

from rsl_rl_tt.testing.envs import Tracking12
from rsl_rl_tt.testing.reference import REF_SPECS, build_distillation_runner
from rsl_rl_tt.tt_common import pad_matrix, stage_obs

ENV = "tracking12"
STEPS = 8
NUM_ENVS = 256  # per step; 256 / n_chips must be a multiple of 32 -> n in {1, 2, 4, 8}
SEED = 0
REFERENCE = "mc_step_reference_distill.npz"
# the same bound as the PPO multi-chip equivalence (the deviation as a fraction of how far the update moved the outputs)
TOLERANCE = 2e-2
FORWARD_ATOL = 1e-3
ALGORITHM = {"num_learning_epochs": 2, "gradient_length": 6, "loss_type": "mse", "max_grad_norm": 1.0, "learning_rate": 1e-3}


def make_runner(mesh_shape: list[int], teacher_ckpt: str):
    """The TTDistillation runner of the test (eager; no rollout is ever run on it). The teacher is the one of `teacher_ckpt` (an RL checkpoint)."""
    import dataclasses

    spec = dataclasses.replace(REF_SPECS[ENV], num_envs=NUM_ENVS, num_steps=STEPS, iterations=1)
    runner, _, _ = build_distillation_runner(ENV, SEED, None, teacher_ckpt, tt=True, tt_cfg={"mesh_shape": list(mesh_shape)}, algorithm=ALGORITHM, spec=spec)
    return runner


def _obs(rows: int, seed: int) -> TensorDict:
    g = torch.Generator().manual_seed(seed)
    return TensorDict({k: torch.randn(rows, d, generator=g) for k, d in Tracking12.obs_group_dims.items()}, batch_size=[rows])


def fill_storage(alg: Any) -> TensorDict:
    """Store the synthetic rollout (STEPS steps of NUM_ENVS rows) in the device storage; returns the observations of all steps."""
    ctx = alg.ctx
    obs = _obs(STEPS * NUM_ENVS, 1)
    with torch.no_grad():
        teacher = alg._raw_teacher(obs)  # the deterministic action of the teacher
    for t in range(STEPS):
        sl = slice(t * NUM_ENVS, (t + 1) * NUM_ENVS)
        o = ctx.upload(stage_obs(obs[sl], alg.tt_student.obs_groups, alg.tt_student.obs_dim_p), op="H-1", batch_sharded=True)
        a = ctx.upload(pad_matrix(teacher[sl], NUM_ENVS, alg.tt_teacher.output_dim_p), op="H-1", batch_sharded=True)
        alg.storage.add(o, a)
    return obs


def run_update(alg: Any) -> dict:
    """One `update()` on the synthetic rollout: the student's mean action on a fixed evaluation set before and after, and the loss."""
    ctx = alg.ctx
    eval_obs = _obs(512, 2)
    out = lambda: ctx.download(alg.tt_student.forward(alg.tt_student.obs_to_device(eval_obs)), op="H-2")[:, : alg.tt_student.output_dim]
    before = out()
    fill_storage(alg)
    loss = alg.update()["behavior"]
    return {"before": before, "after": out(), "loss": loss}


def save_reference(path, res: dict) -> None:
    import numpy as np

    np.savez_compressed(path, loss=np.array([res["loss"]], dtype=np.float64), before=res["before"].numpy(), after=res["after"].numpy())


def load_reference(path) -> dict:
    import numpy as np

    z = np.load(path)
    return {"loss": float(z["loss"][0]), "before": torch.from_numpy(z["before"]), "after": torch.from_numpy(z["after"])}
