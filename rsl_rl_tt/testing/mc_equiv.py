"""Phase 6: N chips vs ONE chip on the same global samples (BRIEF Phase 6 test design, ADR-0004).

The data-parallel update is "every chip computes the loss and gradient of ITS mini-batch, the gradients are averaged over the chips, every chip takes the same
Adam step". On the same samples that equals one chip stepping on the UNION of the chips' mini-batches (mean of equal-sized local means = the global mean), so the
two must agree up to floating-point summation order. This module builds the identical synthetic samples for any chip count and runs K mini-batch steps:

* the samples form K blocks of `UNION_ROWS` rows (block k = the union mini-batch k); a chip count n gives chip c the c-th `UNION_ROWS / n` slice of every block, so
  the union of the chips' mini-batch k is exactly block k, whatever n is (the 1-chip run steps on the blocks themselves);
* rollout, GAE and shuffling are tested separately; here the stored table of `TTPPO.update` is filled directly and `_minibatch_step` runs eagerly, which isolates what
  the multi-chip design adds: chip-local loss -> gradient exchange -> per-model clip -> Adam, and the KL mean / learning rate.

`run_steps` needs an open mesh (a device job); everything else is host torch. The 1-chip reference is generated by `scripts/mc_step_reference.py` and committed under
`tests/tt/data/` (a few hundred KB), so the N-chip tests can compare against it.
"""

from __future__ import annotations

from typing import Any

import torch
from tensordict import TensorDict

from rsl_rl_tt.testing.envs import Tracking12
from rsl_rl_tt.testing.reference import REF_SPECS, RefSpec, build_reference_runner
from rsl_rl_tt.tt_common import pad_matrix, stage_obs

UNION_ROWS = 512  # rows of one union mini-batch (all chips together); 512 / n must be a multiple of 32 -> n in {1, 2, 4, 8, 16}
# Function-space tolerance of the N-chip vs 1-chip comparison, as a fraction of how far the steps moved the outputs. Chosen BEFORE the first measurement from the two
# sources of difference: (a) the summation order of the gradient mean (1e-7 relative, i.e. ~1e-6 of the update size), (b) a clipped-objective gate that sits within 1e-7 of
# its boundary flips for at most a couple of the 512 rows of a mini-batch (~0.2 % of that mini-batch's gradient, 3 steps): 2 % leaves an order of magnitude of headroom.
TOLERANCE = 2e-2
# Absolute bound on the difference between the forward outputs of an N-chip and the 1-chip run (outputs are O(0.5)): the matmul accumulation order depends on the rows per
# chip (measured max 1.2e-4); the TT-vs-float64 error of either run is 1.7e-3 (TOLERANCES.md), so 1e-3 is well inside the known noise floor.
FORWARD_ATOL = 1e-3
STEPS = 3  # mini-batch steps (adaptive learning rate included: the KL of the 2nd and 3rd step is non-zero)
ENV = "tracking12"  # separate actor / critic observation groups (36 / 84), 12 actions
SEED = 0
REFERENCE = "mc_step_reference.npz"  # .npz, not .pt: checkpoints (*.pt) are git-ignored on purpose (BRIEF 2-10); this is a small test fixture
REFERENCE_HETERO = "mc_step_reference_hetero.npz"  # the same with a heteroscedastic actor (Phase 8.1)


def make_runner(mesh_shape: list[int], hetero: bool = False):
    """The TTPPO runner of the test (eager, no rollout is ever run on it); `hetero`: a heteroscedastic Gaussian actor (state-dependent std)."""
    base = REF_SPECS[ENV]
    spec = RefSpec(num_envs=256, num_steps=8, iterations=1, hidden=base.hidden, algorithm={**base.algorithm, "num_mini_batches": 4, "num_learning_epochs": 1},
                   **({"distribution": "HeteroscedasticGaussianDistribution"} if hetero else {}))
    runner, _, _ = build_reference_runner(ENV, SEED, None, spec, tt=True, tt_cfg={"mesh_shape": list(mesh_shape)})
    return runner


def _obs(rows: int, seed: int) -> TensorDict:
    g = torch.Generator().manual_seed(seed)
    return TensorDict({k: torch.randn(rows, d, generator=g) for k, d in Tracking12.obs_group_dims.items()}, batch_size=[rows])


def make_pool(alg: Any, seed: int = 1) -> tuple[torch.Tensor, TensorDict]:
    """The host table [STEPS * UNION_ROWS, width] in the layout of `TTRolloutStorage` (actor obs | critic obs | action | old mean | value, return, advantage, old
    log-prob), computed with the UPSTREAM torch models of the runner (identical in every run: same seed), plus the observations it was built from."""
    st = alg.storage
    rows = STEPS * UNION_ROWS
    g = torch.Generator().manual_seed(seed + 100)
    obs = _obs(rows, seed)
    actor, critic = alg._raw_actor, alg._raw_critic
    with torch.no_grad():
        mean = actor(obs)  # deterministic output = the distribution mean
        value = critic(obs)[:, 0]
        if alg.hetero:
            actor(obs, stochastic_output=True)
            std = actor.output_std.clone()  # [rows, A]: every row has its own std
        else:
            std = alg.tt_actor.distribution.host_std()[: mean.shape[1]]
        action = mean + std * torch.randn(mean.shape, generator=g)
        old_mean = mean + 0.05 * torch.randn(mean.shape, generator=g)  # the policy moved a little since the rollout: ratios and KL are not trivial
        if alg.hetero:
            std = std * (1.0 + 0.1 * torch.rand(std.shape, generator=g))  # ... and so did the std (the stored one differs from the current one)
        old_logp = torch.distributions.Normal(old_mean, std).log_prob(action).sum(-1)
        old_value = value + 0.1 * torch.randn(rows, generator=g)
        returns = value + torch.randn(rows, generator=g)
        adv = torch.randn(rows, generator=g)
        adv = (adv - adv.mean()) / (adv.std() + 1e-8)
    table = torch.zeros(rows, st.width)
    table[:, st.col_actor : st.col_actor + st.actor_dim_p] = stage_obs(obs, alg.tt_actor.obs_groups, st.actor_dim_p)
    if not st.share_obs:
        table[:, st.col_critic : st.col_critic + st.critic_dim_p] = stage_obs(obs, alg.tt_critic.obs_groups, st.critic_dim_p)
    table[:, st.col_action : st.col_action + st.act_dim_p] = pad_matrix(action, rows, st.act_dim_p)
    table[:, st.col_mean : st.col_mean + st.act_dim_p] = pad_matrix(old_mean, rows, st.act_dim_p)
    if alg.hetero:
        table[:, st.col_std : st.col_std + st.act_dim_p] = pad_matrix(std, rows, st.act_dim_p, fill=1.0)  # a stored std is 1 in the padded columns
    for name, col in (("value", old_value), ("returns", returns), ("advantages", adv), ("old_logp", old_logp)):
        table[:, st.col_scalars + {"value": 0, "returns": 1, "advantages": 2, "old_logp": 3}[name]] = col
    return table, obs


def chip_layout(pool: torch.Tensor, n_chips: int) -> torch.Tensor:
    """Rows of the pool arranged for `n_chips` chips: chip c holds the c-th slice of every union block, its mini-batch k = its local rows
    [k * m, (k + 1) * m), m = UNION_ROWS / n_chips. The chips' tables are stacked one after the other (the batch-sharded upload gives chip c its own table)."""
    assert UNION_ROWS % (n_chips * 32) == 0, n_chips
    m = UNION_ROWS // n_chips
    blocks = pool.reshape(STEPS, UNION_ROWS, pool.shape[1])
    return torch.cat([blocks[:, c * m : (c + 1) * m, :].reshape(STEPS * m, pool.shape[1]) for c in range(n_chips)])


def run_steps(alg: Any, pool: torch.Tensor, eval_obs: TensorDict) -> dict:
    """Run `STEPS` eager mini-batch steps on `alg` (any chip count) over `pool` and return the state and the policy / value outputs on `eval_obs` before and after."""
    from tests.tt.test_tt_update import tt_params  # parameters as host tensors in torch layout (same helper as the Phase 3 tests)

    ctx = alg.ctx
    n = ctx.n_chips
    dist = alg.tt_actor.distribution

    def outputs():
        a = ctx.download(alg.tt_actor.forward(alg.tt_actor.obs_to_device(eval_obs)), op="H-2")
        a = torch.cat([a[:, : dist.dim], a[:, dist.dim_p : dist.dim_p + dist.dim]], dim=1) if alg.hetero else a[:, : alg.tt_actor.output_dim]  # hetero: mean and std head
        c = ctx.download(alg.tt_critic.forward(alg.tt_critic.obs_to_device(eval_obs)), op="H-2")[:, :1]
        return a, c

    before = outputs()
    alg._buf["update.table"] = ctx.upload(chip_layout(pool, n), op="H-6", batch_sharded=True)
    if not alg.hetero:
        for key, value in (("update.old_var", dist.var), ("update.old_log_std", dist.log_std)):
            alg._buf[key] = ctx.put(alg._buf.get(key), value)
    lrs = []
    for k in range(STEPS):
        alg.adam.prepare_step()
        alg._minibatch_step(k, UNION_ROWS // n)
        lrs.append(float(ctx.download(alg.lr_sched.lr, op="H-5", batch_sharded=False)[0, 0]))
    after = outputs()
    return {
        "params": tt_params(alg),
        "adam_m": [ctx.download(t, op="H-6", batch_sharded=False) for t in alg.adam.m],
        "adam_v": [ctx.download(t, op="H-6", batch_sharded=False) for t in alg.adam.v],
        "lrs": lrs,
        "actor_before": before[0], "critic_before": before[1], "actor_after": after[0], "critic_after": after[1],
    }


def save_reference(path, res: dict) -> None:
    """The 1-chip reference: the learning-rate sequence and the policy / value outputs on the evaluation observations before and after the steps."""
    import numpy as np

    np.savez_compressed(path, lrs=np.array(res["lrs"], dtype=np.float64), **{k: res[k].numpy() for k in ("actor_before", "critic_before", "actor_after", "critic_after")})


def load_reference(path) -> dict:
    import numpy as np

    z = np.load(path)
    return {"lrs": [float(v) for v in z["lrs"]], **{k: torch.from_numpy(z[k]) for k in ("actor_before", "critic_before", "actor_after", "critic_after")}}
